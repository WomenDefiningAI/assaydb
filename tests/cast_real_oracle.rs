fn oracle() -> Vec<Json> {
    // The checked-in expected bits were generated by the exact amalgamation in
    // the frozen SLT check-in. No system SQLite or network is needed for tests.
    let result: Json =
        serde_json::from_str(include_str!("fixtures/sqlite-real-boundaries.json")).unwrap();
    assert_eq!(
        result["sqllogictest_checkin"],
        "ab599cbdd0976a63c5cfc7755588f716a7621f27"
    );
    assert_eq!(result["sqlite_version"], "3.54.0");
    assert_eq!(
        result["sqlite_source_id"],
        "2026-10-07 10:41:59 d232720b7932c1cebe4cf5b1a1e9096889e1807844351390149dfeb2ea7fc304"
    );
    assert_eq!(
        result["amalgamation_sha256"],
        "b739c477092f587417d402fe227eb13c0a83f7534e87082f4a1b80d429a57931"
    );
    assert_eq!(
        result["rows"]
            .as_array()
            .unwrap()
            .iter()
            .map(|r| r["text"].as_str().unwrap())
            .collect::<Vec<_>>(),
        CASES
    );
    result["rows"].as_array().unwrap().clone()
}

#[test]
fn real_cast_matches_sqlite_bits_at_subnormal_exponent_and_adjacent_boundaries() {
    let expected = oracle();
    assert_eq!(expected.len(), CASES.len());
    // Both entry points reach the same cast implementation: SQL binding and
    // actual column arrays, including BLOB numeric prefixes, NULLs and leases.
    for row in expected {
        let text = row["text"].as_str().unwrap();
        let finite = row["finite"].as_bool().unwrap();
        let expected_bits = u64::from_str_radix(row["bits"].as_str().unwrap(), 16).unwrap();
        for workers in [1, 10] {
            for optimized in [false, true] {
                let options = Options {
                    workers,
                    relational_optimizations: optimized,
                    ..Options::default()
                };
                let sql = format!("SELECT CAST('{}' AS REAL)", text.replace('\'', "''"));
                let result =
                    prepare(&sql, &HashMap::new(), &options).and_then(|p| execute(&p, &options));
                if finite {
                    let batch: RecordBatch = result
                        .unwrap_or_else(|e| panic!("{text:?}: {e}"))
                        .batch
                        .clone();
                    let actual = batch
                        .column(0)
                        .as_any()
                        .downcast_ref::<Float64Array>()
                        .unwrap()
                        .value(0)
                        .to_bits();
                    assert_eq!(
                        actual, expected_bits,
                        "SQLite REAL mismatch for {text:?}, workers={workers}, optimized={optimized}"
                    );
                } else {
                    // This boundary is intentionally unsupported, never converted to
                    // NULL or a finite invented result to satisfy the fixture.
                    assert!(
                        result
                            .err()
                            .unwrap()
                            .contains("unsupported: REAL cast nonfinite result"),
                        "{text:?}"
                    );
                }
            }
        }
        for binary in [false, true] {
            let budget = Budget::new(1 << 20);
            let array: ArrayRef = if binary {
                Arc::new(BinaryArray::from(vec![Some(text.as_bytes()), None]))
            } else {
                Arc::new(StringArray::from(vec![Some(text), None]))
            };
            let input = Input {
                columns: vec![Some(Value::adopt(array, &budget).unwrap())],
                len: 2,
            };
            let expr = Expr {
                kind: Kind::Cast(Box::new(Expr {
                    kind: Kind::Column(0),
                    ty: if binary { Type::Binary } else { Type::Text },
                })),
                ty: Type::Float,
            };
            let baseline = budget.used();
            let result = expr.eval(&input, &budget);
            if finite {
                let result = result.unwrap();
                let values = result
                    .array
                    .as_any()
                    .downcast_ref::<Float64Array>()
                    .unwrap();
                assert_eq!(
                    values
                        .iter()
                        .map(|v| v.map(f64::to_bits))
                        .collect::<Vec<_>>(),
                    vec![Some(expected_bits), None],
                    "{text:?}, binary={binary}"
                );
                drop(input);
                assert!(budget.used() >= result.array.get_array_memory_size());
                drop(result);
            } else {
                assert!(
                    result
                        .err()
                        .unwrap()
                        .contains("unsupported: REAL cast nonfinite result")
                );
                assert_eq!(budget.used(), baseline);
                drop(input);
            }
            assert_eq!(budget.used(), 0);
        }
    }
}
